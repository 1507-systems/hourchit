#!/usr/bin/env node
/**
 * Build the tenant profile registry from whatever is sitting in profiles/.
 *
 * Why codegen instead of a hand-maintained list of imports: the open-source
 * core ships only core.json and example.json, while real tenants live in a
 * separate private repo and are copied in at deploy time. A committed import
 * list would either name tenants that aren't there (build break) or force the
 * public repo to reference private files. Globbing the directory keeps the core
 * honest, it knows about exactly the profiles present, no more.
 *
 * The output is gitignored. Regenerate with `npm run profiles`; the dev, test,
 * typecheck, and deploy scripts all do it for you via npm pre-hooks.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const profilesDir = join(root, 'profiles');
const outPath = join(root, 'src', 'config', 'profiles.generated.ts');

const files = readdirSync(profilesDir)
  .filter((f) => f.endsWith('.json'))
  .sort();

if (files.length === 0) {
  console.error(`No profiles found in ${profilesDir}. At minimum core.json must exist.`);
  process.exit(1);
}

const entries = [];
for (const file of files) {
  const raw = readFileSync(join(profilesDir, file), 'utf8');
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch (err) {
    console.error(`profiles/${file} is not valid JSON: ${err.message}`);
    process.exit(1);
  }
  // The filename and the key inside must agree, or TENANT_PROFILE lookups
  // silently miss and the deploy serves the wrong tenant's branding.
  const expected = file.replace(/\.json$/, '');
  if (parsed.key !== expected) {
    console.error(
      `profiles/${file} has key ${JSON.stringify(parsed.key)} but must be ${JSON.stringify(expected)} to match its filename.`,
    );
    process.exit(1);
  }
  entries.push([parsed.key, parsed]);
}

const body = entries
  .map(([key, profile]) => `  ${JSON.stringify(key)}: ${JSON.stringify(profile, null, 2).replace(/\n/g, '\n  ')},`)
  .join('\n');

const out = `// AUTO-GENERATED by scripts/generate-profiles.mjs, do not edit, do not commit.
// Regenerate with: npm run profiles
import type { TenantProfile } from './profile';

export const PROFILES: Record<string, TenantProfile> = {
${body}
};
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out);
console.error(`Generated ${files.length} profile(s): ${entries.map(([k]) => k).join(', ')}`);
