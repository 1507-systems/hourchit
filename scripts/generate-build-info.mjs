#!/usr/bin/env node
/**
 * Stamp the build with the commit it came from, so a deploy can be verified
 * from outside by reading /health rather than assumed to have worked.
 *
 * A deploy that silently no-ops looks exactly like a successful one from the
 * CLI's output; the only reliable check is asking the running Worker what it
 * is. Workers Builds and GitHub Actions each expose the commit in their own
 * variable, so prefer those and fall back to asking git directly for local
 * builds.
 *
 * Output is gitignored — it changes every commit and would be pure diff noise.
 */
import { writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, '..', 'src', 'build-info.generated.ts');

function resolveSha() {
  // Workers Builds injects this; GitHub Actions injects GITHUB_SHA.
  const fromCi = process.env.WORKERS_CI_COMMIT_SHA || process.env.GITHUB_SHA;
  if (fromCi) return fromCi.slice(0, 12);
  try {
    return execFileSync('git', ['rev-parse', '--short=12', 'HEAD'], {
      cwd: join(here, '..'),
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    // A source tarball with no git history and no CI variables. Better to say
    // so than to invent a plausible-looking value.
    return 'unknown';
  }
}

const sha = resolveSha();

writeFileSync(
  outPath,
  `// AUTO-GENERATED by scripts/generate-build-info.mjs — do not edit, do not commit.
export const GIT_SHA = ${JSON.stringify(sha)};
`,
);
console.error(`Build stamped as ${sha}`);
