#!/usr/bin/env node
/**
 * Stamp the build with the commits it came from, so a deploy can be verified
 * from outside by reading /health rather than assumed to have worked.
 *
 * A deploy that silently no-ops looks exactly like a successful one from the
 * CLI's output; the only reliable check is asking the running Worker what it is.
 *
 * TWO identities, because a tenant deploy builds TWO repositories:
 *
 *   GIT_SHA     the commit of THIS tree, the application code that is running.
 *               Taken from git whenever there is a checkout, because in a tenant
 *               build the CI-provided sha belongs to the *config* repo, not to
 *               the core; reporting that as the running version would make a
 *               drift check compare two unrelated histories.
 *
 *   CONFIG_SHA  the commit CI is actually building, when it differs from the
 *               core, i.e. the private tenant-config repo that pinned this core
 *               and supplied the profile and Worker config. Empty when the core
 *               repo is itself the thing being built.
 *
 * Output is gitignored, it changes every commit and would be pure diff noise.
 */
import { writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const outPath = join(root, 'src', 'build-info.generated.ts');

const SHORT = 12;

/** This tree's own commit. Works in a `--depth 1` clone. */
function gitSha() {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    // A source tarball with no git history.
    return null;
  }
}

/** Workers Builds injects WORKERS_CI_COMMIT_SHA; GitHub Actions injects GITHUB_SHA. */
function ciSha() {
  return process.env.WORKERS_CI_COMMIT_SHA || process.env.GITHUB_SHA || null;
}

const git = gitSha();
const ci = ciSha();

// Fall back to the CI sha only when there is no checkout at all, and say
// "unknown" rather than invent a plausible-looking value.
const core = git ?? ci ?? 'unknown';

// Only meaningful when CI is building a different repository than this one.
const config = ci && ci !== core ? ci : '';

const short = (sha) => (sha === 'unknown' ? sha : sha.slice(0, SHORT));

writeFileSync(
  outPath,
  `// AUTO-GENERATED by scripts/generate-build-info.mjs, do not edit, do not commit.

/** Commit of the HourChit core that is running. */
export const GIT_SHA = ${JSON.stringify(short(core))};

/**
 * Commit of the tenant-config repo that produced this deploy, or '' when the
 * core repo was built directly.
 */
export const CONFIG_SHA = ${JSON.stringify(config ? short(config) : '')};
`,
);
console.error(
  config
    ? `Build stamped as core ${short(core)}, config ${short(config)}`
    : `Build stamped as core ${short(core)}`,
);
